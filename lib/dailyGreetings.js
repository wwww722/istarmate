// 用日期字符串生成稳定 hash
function dateHash(dateStr) {
  let h = 0;
  for (let i = 0; i < dateStr.length; i++) {
    h = (h * 31 + dateStr.charCodeAt(i)) >>> 0;
  }
  return h;
}

// 取今天的一句。char: 'anhe' | 'yusheng'
export function getTodayGreeting(char, date = new Date()) {
  const dateStr = date.toISOString().slice(0, 10);
  const lines = char === "yusheng" ? YUSHENG_LINES : ANHE_LINES;
  // 许安和和余生用不同偏移，避免"同一天两人同下标"的巧合感
  const offset = char === "yusheng" ? 7 : 0;
  return lines[(dateHash(dateStr) + offset) % lines.length];
}
